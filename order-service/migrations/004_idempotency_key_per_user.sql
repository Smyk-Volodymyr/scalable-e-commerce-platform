-- Номер 003 навмисно пропущено: під ним була спроба цієї ж правки, яку відкотили
-- до коміту. У жодній базі вона не застосовувалась, тож 003 просто не існує.

-- Ключ ідемпотентності має бути унікальним У ПАРІ з користувачем.
-- Репозиторій завжди шукає рядок як (key, user_id) — див. findByIdempotencyKey —
-- а PRIMARY KEY лише по key робив простір ключів глобальним на весь сервіс.
-- Наслідок: якщо два користувачі згенерували однаковий Idempotency-Key, checkout
-- другого падав з 23505 на idempotency_keys_pkey. Причому падав уже ПІСЛЯ того, як
-- створено резерв на складі: клієнт отримував 500, а товар лишався зарезервованим
-- до спрацювання TTL. Клієнт не міг ані повторити запит, ані дізнатись причину.
--
-- Складений ключ прибирає колізію між користувачами й водночас лишає захист
-- від дублю в межах одного користувача — саме те, заради чого ідемпотентність і є.
-- Індекс складеного PRIMARY KEY починається з key, тож пошук парою лишається
-- індексним, окремий індекс не потрібен.

-- Перший рядок робить міграцію безпечною до повторного запуску: новий ключ
-- отримує те саме типове ім'я idempotency_keys_pkey, тож повторний прогін
-- просто перестворить його.
ALTER TABLE idempotency_keys DROP CONSTRAINT IF EXISTS idempotency_keys_pkey;
ALTER TABLE idempotency_keys ADD PRIMARY KEY (key, user_id);
